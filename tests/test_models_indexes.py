"""Schema tests for the V3 migrations that carry a guarantee no dataclass can.

`embed_tokens` (M7, F4): one *active* token per website plus a hash that is
unique table-wide. The first is a **partial** unique index, easy to get subtly
wrong — a plain unique index on `website_id` would block the revoked history that
rotation depends on. So these tests pin the model declaration, the compiled
PostgreSQL DDL, and the migration that ships it.

`topic_clusters` / `topic_cluster_runs` (M8, F2): one run per company+window and
one row per cluster identity inside a window. Both are plain unique constraints,
but they are the whole idempotency story for the clustering worker, and the
migration is autogenerated — which means the four known drift `ALTER`s come with
it every time. The migration tests assert the drift was *not* taken, because an
accidental `ALTER COLUMN … TYPE DATETIME` silently drops the timezone from a
column that is compared with aware datetimes.
"""

import unittest
from pathlib import Path

from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex

from site_gpt.app import models
from site_gpt.app.core.config import EMBEDDING_DIMENSIONS

ROOT = Path(__file__).resolve().parent.parent
M7_REVISION = "76f46b510350"
M7_PATH = ROOT / "alembic" / "versions" / f"{M7_REVISION}_v3_m7_embed_tokens.py"
M7_PARENT = "c9d3e5a71b28"
M8_REVISION = "afef1e91e0b5"
M8_PATH = ROOT / "alembic" / "versions" / f"{M8_REVISION}_v3_m8_topic_clusters.py"
ACTIVE_INDEX = "uq_embed_tokens_website_id_active"


def _index(name: str):
    return next(
        (item for item in models.EmbedToken.__table__.indexes if item.name == name),
        None,
    )


class EmbedTokenModelTests(unittest.TestCase):
    def test_table_and_columns(self):
        table = models.EmbedToken.__table__

        self.assertEqual(table.name, "embed_tokens")
        self.assertEqual(table.columns["token_prefix"].type.length, 12)
        self.assertEqual(table.columns["token_hash"].type.length, 64)

    def test_website_fk_cascades(self):
        # Deleting a website must not leave tokens that could still be presented.
        column = models.EmbedToken.__table__.columns["website_id"]
        foreign_key = next(iter(column.foreign_keys))

        self.assertEqual(foreign_key.column.table.name, "websites")
        self.assertEqual(foreign_key.ondelete, "CASCADE")
        self.assertFalse(column.nullable)

    def test_hash_is_unique(self):
        uniques = {
            tuple(sorted(column.name for column in constraint.columns))
            for constraint in models.EmbedToken.__table__.constraints
            if constraint.__class__.__name__ == "UniqueConstraint"
        }

        self.assertIn(("token_hash",), uniques)

    def test_only_active_tokens_are_unique_per_website(self):
        # Revoked rows must be allowed to coexist, so this has to be partial.
        index = _index(ACTIVE_INDEX)

        self.assertIsNotNone(index, f"EmbedToken must declare {ACTIVE_INDEX}")
        self.assertTrue(index.unique)
        self.assertEqual([column.name for column in index.columns], ["website_id"])
        self.assertEqual(
            str(index.dialect_options["postgresql"]["where"]),
            "revoked_at IS NULL",
        )
        # The test suite runs on SQLite; the same predicate there keeps
        # `test_embed_tokens` able to prove that rotation may keep revoked rows.
        self.assertEqual(
            str(index.dialect_options["sqlite"]["where"]),
            "revoked_at IS NULL",
        )

    def test_compiled_ddl_is_a_partial_unique_index(self):
        ddl = str(
            CreateIndex(_index(ACTIVE_INDEX)).compile(dialect=postgresql.dialect())
        )

        self.assertIn("CREATE UNIQUE INDEX", ddl)
        self.assertIn("WHERE revoked_at IS NULL", ddl)

    def test_revoked_and_last_used_are_timezone_aware(self):
        # SessionToken set the precedent; naive columns here would make
        # `last_used_at` throttling compare a naive value with an aware one.
        for name in ("revoked_at", "last_used_at"):
            column = models.EmbedToken.__table__.columns[name]
            self.assertTrue(column.nullable)
            self.assertTrue(column.type.timezone, f"{name} must be timezone-aware")

    def test_website_owns_its_tokens(self):
        relationship = models.Website.__mapper__.relationships["embed_tokens"]

        self.assertEqual(relationship.mapper.class_.__name__, "EmbedToken")
        self.assertTrue(relationship.passive_deletes)


class EmbedTokenMigrationTests(unittest.TestCase):
    def setUp(self):
        self.source = M7_PATH.read_text(encoding="utf-8")

    def test_migration_exists_and_chains_from_the_v2_head(self):
        self.assertTrue(M7_PATH.exists(), f"missing migration {M7_PATH.name}")
        self.assertIn(
            "down_revision: Union[str, Sequence[str], None] = 'c9d3e5a71b28'",
            self.source,
        )

    def test_migration_creates_the_same_table(self):
        for column in (
            "website_id",
            "token_prefix",
            "token_hash",
            "revoked_at",
            "last_used_at",
        ):
            self.assertIn(f"'{column}'", self.source)
        self.assertIn("sa.UniqueConstraint('token_hash')", self.source)
        self.assertIn("ondelete='CASCADE'", self.source)

    def test_migration_creates_the_partial_unique_index(self):
        self.assertIn(ACTIVE_INDEX, self.source)
        self.assertIn("unique=True", self.source)
        self.assertIn("postgresql_where=sa.text('revoked_at IS NULL')", self.source)

    def test_new_table_indexes_are_built_transactionally(self):
        # `embed_tokens` has no traffic yet, so the CONCURRENTLY dance (and its
        # non-atomic risk) is neither needed nor wanted.
        self.assertNotIn("autocommit_block()", self.source)
        self.assertNotIn("postgresql_concurrently=True", self.source)

    def test_downgrade_removes_table_and_index(self):
        downgrade = self.source.split("def downgrade()", 1)[1]

        self.assertIn("drop_index", downgrade)
        self.assertIn(ACTIVE_INDEX, downgrade)
        self.assertIn("drop_table('embed_tokens')", downgrade)

    def test_m7_still_chains_from_the_v2_head(self):
        config = Config(str(ROOT / "alembic.ini"))
        config.set_main_option("script_location", str(ROOT / "alembic"))
        script = ScriptDirectory.from_config(config)

        # M8 is the head now; M7 must still be exactly one step behind it and
        # still chained from the V2 head, or M8 was rebased onto the wrong parent.
        self.assertEqual(script.get_heads(), [M8_REVISION])
        self.assertEqual(script.get_revision(M8_REVISION).down_revision, M7_REVISION)
        self.assertEqual(script.get_revision(M7_REVISION).down_revision, M7_PARENT)


def _unique_column_sets(model):
    return {
        tuple(sorted(column.name for column in constraint.columns))
        for constraint in model.__table__.constraints
        if constraint.__class__.__name__ == "UniqueConstraint"
    }


class TopicClusterSchemaTests(unittest.TestCase):
    def test_table_and_columns(self):
        table = models.TopicCluster.__table__

        self.assertEqual(table.name, "topic_clusters")
        self.assertEqual(table.columns["cluster_key"].type.length, 32)
        self.assertEqual(table.columns["label"].type.length, 120)
        self.assertTrue(table.columns["summary"].nullable)

    def test_company_fk_cascades(self):
        column = models.TopicCluster.__table__.columns["company_id"]
        foreign_key = next(iter(column.foreign_keys))

        self.assertEqual(foreign_key.column.table.name, "companies")
        self.assertEqual(foreign_key.ondelete, "CASCADE")
        self.assertFalse(column.nullable)

    def test_a_cluster_identity_is_unique_inside_its_window(self):
        # This is what a rebuild replaces rows through; without it every run
        # would append a second copy of the same cluster.
        self.assertIn(
            ("cluster_key", "company_id", "period_start"),
            _unique_column_sets(models.TopicCluster),
        )

    def test_centroid_matches_the_embedding_dimension(self):
        column = models.TopicCluster.__table__.columns["centroid"]

        self.assertEqual(column.type.dim, EMBEDDING_DIMENSIONS)
        # Nullable: a cluster whose centroid could not be embedded is still
        # recorded (with its counts) rather than dropped silently.
        self.assertTrue(column.nullable)

    def test_period_is_timezone_aware(self):
        # Naive would make `period_start <= moment` ambiguous on Postgres.
        self.assertTrue(models.TopicCluster.__table__.columns["period_start"].type.timezone)

    def test_counts_are_required_integers(self):
        table = models.TopicCluster.__table__

        for name in ("sampled_messages", "eligible_messages"):
            self.assertFalse(table.columns[name].nullable, name)
            self.assertEqual(table.columns[name].type.python_type, int)

    def test_purge_index_covers_company_and_created_at(self):
        names = {index.name for index in models.TopicCluster.__table__.indexes}

        self.assertIn("idx_topic_clusters_company_id_created_at", names)


class TopicClusterRunSchemaTests(unittest.TestCase):
    def test_one_run_per_company_and_window(self):
        self.assertIn(
            ("company_id", "period_start"),
            _unique_column_sets(models.TopicClusterRun),
        )

    def test_company_fk_cascades(self):
        column = models.TopicClusterRun.__table__.columns["company_id"]
        foreign_key = next(iter(column.foreign_keys))

        self.assertEqual(foreign_key.column.table.name, "companies")
        self.assertEqual(foreign_key.ondelete, "CASCADE")

    def test_status_is_bounded_by_the_database(self):
        checks = {
            constraint.name: str(constraint.sqltext)
            for constraint in models.TopicClusterRun.__table__.constraints
            if constraint.__class__.__name__ == "CheckConstraint"
        }

        self.assertIn("ck_topic_cluster_runs_status", checks)
        for status in ("running", "completed", "failed"):
            self.assertIn(status, checks["ck_topic_cluster_runs_status"])

    def test_stale_recovery_index_covers_status_and_claim_time(self):
        names = {index.name for index in models.TopicClusterRun.__table__.indexes}

        self.assertIn("idx_topic_cluster_runs_status_claimed_at", names)
        self.assertIn("idx_topic_cluster_runs_company_id_created_at", names)

    def test_error_metadata_is_bounded(self):
        column = models.TopicClusterRun.__table__.columns["error"]

        self.assertTrue(column.nullable)
        self.assertEqual(column.type.length, 500)

    def test_timestamps_are_timezone_aware(self):
        table = models.TopicClusterRun.__table__

        self.assertTrue(table.columns["period_start"].type.timezone)
        for name in ("claimed_at", "completed_at"):
            self.assertTrue(table.columns[name].type.timezone, name)
            self.assertTrue(table.columns[name].nullable, name)


class TopicClusterMigrationTests(unittest.TestCase):
    def setUp(self):
        self.source = M8_PATH.read_text(encoding="utf-8")

    def test_migration_exists_and_chains_from_m7(self):
        self.assertTrue(M8_PATH.exists(), f"missing migration {M8_PATH.name}")
        self.assertIn(
            "down_revision: Union[str, Sequence[str], None] = '76f46b510350'",
            self.source,
        )

    def test_migration_creates_both_tables_and_their_identities(self):
        self.assertIn("create_table(\n        'topic_clusters',", self.source)
        self.assertIn("create_table(\n        'topic_cluster_runs',", self.source)
        self.assertIn(
            "UniqueConstraint('company_id', 'period_start', 'cluster_key')",
            self.source,
        )
        self.assertIn("UniqueConstraint('company_id', 'period_start')", self.source)
        self.assertIn("name='ck_topic_cluster_runs_status'", self.source)

    def test_centroid_uses_the_same_dimension_as_embeddings(self):
        self.assertIn("from pgvector.sqlalchemy import VECTOR", self.source)
        self.assertIn(f"VECTOR(dim={EMBEDDING_DIMENSIONS})", self.source)

    def test_the_known_drift_was_not_taken(self):
        # Autogenerate proposes these every time; taking one would rewrite a
        # timezone-aware column as naive or churn an unchanged FK.
        self.assertNotIn("alter_column", self.source)
        self.assertNotIn("drop_constraint", self.source)

    def test_new_table_indexes_are_built_transactionally(self):
        self.assertNotIn("autocommit_block()", self.source)
        self.assertNotIn("postgresql_concurrently=True", self.source)

    def test_downgrade_removes_both_tables(self):
        downgrade = self.source.split("def downgrade()", 1)[1]

        self.assertIn("drop_table('topic_clusters')", downgrade)
        self.assertIn("drop_table('topic_cluster_runs')", downgrade)
        self.assertIn("drop_index", downgrade)

    def test_m8_is_the_single_head(self):
        config = Config(str(ROOT / "alembic.ini"))
        config.set_main_option("script_location", str(ROOT / "alembic"))
        script = ScriptDirectory.from_config(config)

        self.assertEqual(script.get_heads(), [M8_REVISION])
        self.assertEqual(script.get_revision(M8_REVISION).down_revision, M7_REVISION)


if __name__ == "__main__":
    unittest.main()
